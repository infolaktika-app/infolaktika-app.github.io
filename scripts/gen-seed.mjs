// Generates supabase/seed.sql from src/data/seed.json (games, achievements,
// daily challenges, settings and the sample comics/books).
// Usage: node scripts/gen-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const seed = JSON.parse(fs.readFileSync(path.join(root, 'src/data/seed.json'), 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = [];
out.push('-- INFOLAKTIKA seed data (generated by scripts/gen-seed.mjs — edit src/data/seed.json instead)');
out.push('begin;');
const s = seed.settings;
out.push(`update public.settings set motivational_message = ${q(s.motivational_message)}, xp_comic = ${s.xp_comic}, xp_book = ${s.xp_book}, xp_daily = ${s.xp_daily}, xp_missions = ${s.xp_missions} where id = 1;`);

for (const a of seed.achievements) {
  out.push(`insert into public.achievements (code, title, description, icon, sort) values (${q(a.code)}, ${q(a.title)}, ${q(a.description)}, ${q(a.icon)}, ${a.sort})
  on conflict (code) do update set title = excluded.title, description = excluded.description, icon = excluded.icon, sort = excluded.sort;`);
}

out.push('delete from public.daily_challenges where id not in (select challenge_id from public.daily_completions);');
seed.daily_challenges.forEach((c, i) => {
  out.push(`insert into public.daily_challenges (id, question, options, answer, explanation) values (${i + 1}, ${q(c.question)}, ${j(c.options)}, ${c.answer}, ${q(c.explanation)})
  on conflict (id) do update set question = excluded.question, options = excluded.options, answer = excluded.answer, explanation = excluded.explanation;`);
});
out.push(`select setval(pg_get_serial_sequence('public.daily_challenges', 'id'), (select max(id) from public.daily_challenges));`);

for (const g of seed.games) {
  out.push(`insert into public.games (slug, title, description, type, category, difficulty, xp_reward, data, sort) values (${q(g.slug)}, ${q(g.title)}, ${q(g.description)}, ${q(g.type)}, ${q(g.category)}, ${q(g.difficulty)}, ${g.xp_reward}, ${j(g.data)}, ${g.sort})
  on conflict (slug) do nothing;`);
}

// Sample content lives in the app's /public/sample folder. The app treats a
// pdf_path / cover_url beginning with "sample/" as a static file, so these
// work without any storage upload. Replace or delete them from the admin panel.
// Later entries are newer, so the last comic/book shows first in the app.
seed.comics.forEach((c, i) => {
  const age = seed.comics.length - 1 - i;
  out.push(`insert into public.comics (id, title, description, category, cover_url, pdf_path, pages, created_at) values (${q(c.id)}, ${q(c.title)}, ${q(c.description)}, ${q(c.category)}, ${q(c.cover_url)}, ${q(c.pdf_path)}, ${c.pages}, now() - interval '${age} days')
  on conflict (id) do nothing;`);
});
for (const b of seed.books) {
  out.push(`insert into public.books (id, title, author, description, category, cover_url, pdf_path, pages) values (${q(b.id)}, ${q(b.title)}, ${q(b.author)}, ${q(b.description)}, ${q(b.category)}, ${q(b.cover_url)}, ${q(b.pdf_path)}, ${b.pages})
  on conflict (id) do nothing;`);
}
out.push('commit;');
fs.writeFileSync(path.join(root, 'supabase/seed.sql'), out.join('\n') + '\n');
console.log('Wrote supabase/seed.sql');
